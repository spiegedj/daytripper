export type PlaceCategory =
	| "temple"
	| "cathedral"
	| "landmark"
	| "museum"
	| "food"
	| "shopping"
	| "nature"
	| "hotel"
	| "station"
	| "airport";

export type TravelMode =
	| "walk"
	| "subway"
	| "train"
	| "shinkansen"
	| "bus"
	| "tram"
	| "ferry"
	| "boat"
	| "ropeway"
	| "flight"
	| "taxi"
	| "car"
	| "bike";

/** A point on the map in WGS84 degrees. */
export interface ICoordinates
{
	longitude: number;
	latitude: number;
}

/** A place that can appear in any day's itinerary. Defined once per trip and referenced by id. */
export interface IPlace
{
	id: string;
	name: string;
	localName?: string;
	category: PlaceCategory;
	coordinates: ICoordinates;
	/** URL of a custom illustration. When present the place renders as a freestanding landmark instead of a pin. */
	landmarkIconUrl?: string;
	/** Enlarges slender landmark illustrations so they carry the same visual weight as wide ones. Defaults to 1. */
	landmarkIconScale?: number;
	/** Short, practical travel tips written for this trip. */
	tips?: string[];
}

/** A freely licensed photo with the credit its license requires. */
export interface IPhoto
{
	url: string;
	width: number;
	height: number;
	author: string;
	license: string;
	sourceUrl: string;
}

/** One of the traveler's own photos at a stop, published as a resized copy with its metadata removed by scripts/processTripPhotos.mjs. */
export interface ITripPhoto
{
	/** Path under the site root of the 1600 px copy. */
	path: string;
	/** Path under the site root of the 480 px copy, used on narrow screens. */
	thumbnailPath: string;
	width: number;
	height: number;
	/** Local time the photo was taken, "HH:MM". */
	takenAt: string;
}

/** Background reading and photos for a place, generated from Wikipedia by scripts/fetchPlaceDetails.mjs. */
export interface IPlaceDetails
{
	summary: string;
	wikipediaTitle: string;
	wikipediaUrl: string;
	photos: IPhoto[];
}

/** How the traveler gets to a stop from the previous one. */
export interface ITravelLeg
{
	mode: TravelMode;
	lineName?: string;
	minutes?: number;
	/** True while the route is an estimate rather than a decided plan. */
	isGuess?: boolean;
}

/** One stop within a day. */
export interface IStop
{
	placeId: string;
	/** When the traveler was actually there, in local 24-hour clock time, for trips that already happened. */
	visit?: IVisitTime;
	arrival?: ITravelLeg;
}

/** A local clock-time window, such as 10:24 to 11:17, taken from photo timestamps. */
export interface IVisitTime
{
	start: string;
	/** Omitted for a quick stop with a single moment, like one photo. */
	end?: string;
}

/**
 * One day of the trip. Upcoming trips leave out dates so the public site shows no calendar; trips that already
 * happened carry the real date and are labeled by it.
 */
export interface IDay
{
	dayNumber: number;
	title: string;
	baseCity: string;
	color: string;
	stops: IStop[];
	/** The calendar date as YYYY-MM-DD, only for trips that already happened. */
	date?: string;
	/** Things not decided yet, shown in the timeline as "To be planned" cards. */
	openQuestions?: string[];
}

/** One piece of a real-world leg path, such as the walk to a station or the train ride itself. */
export interface ILegSegment
{
	mode: TravelMode;
	/** [longitude, latitude] pairs. */
	coordinates: [number, number][];
}

/** A city you stay in, used to label the trip overview. Days refer to it through their baseCity name. */
export interface ICity
{
	name: string;
	localName?: string;
	coordinates: ICoordinates;
	/** Where the overview badge sits relative to the city, so nearby cities don't cover each other. Defaults to above. */
	badgePlacement?: "above" | "below";
}

/** A complete trip: its places and its ordered days. */
export interface ITrip
{
	id: string;
	name: string;
	/** A short line under the name in the trip picker, such as "Upcoming" or "October 2024". */
	tagline: string;
	cities: ICity[];
	/** Shows the map's town and city names in this language too, under the English (an OpenStreetMap code such as "ja"). */
	localMapLanguage?: string;
	places: Record<string, IPlace>;
	placeDetails: Record<string, IPlaceDetails>;
	/** Real paths for some legs, keyed "dayNumber:arrivalStopIndex", generated by scripts/fetchTransitRoutes.mjs. Other legs are drawn as curves. */
	legPaths: Record<string, ILegSegment[]>;
	days: IDay[];
	/** The traveler's own photos, keyed "dayNumber:stopIndex". Only past trips have them. */
	tripPhotos?: Record<string, ITripPhoto[]>;
}
